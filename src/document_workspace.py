def attachment_key(url: str) -> str:
    return hashlib.sha1(str(url).encode()).hexdigest()[:16]


@lru_cache(maxsize=1)
def _attachment_kinds() -> dict:
    try:
        return json.loads(ATTACHMENT_KINDS_PATH.read_text(encoding="utf-8")).get("kinds", {})
    except (OSError, ValueError):
        return {}


def decide_kind(name: str, content: str, *, pages: int | None = None, size_kb: float | None = None) -> str:
    """파일 내용 검증 결과로 서류/참고 자료를 정한다.

    content: form(신청서 칸 있음) / no_form / scanned / unsupported.
    신청서가 들어 있어도 두꺼운 사업안내·지침은 참고 자료다(PDF 10쪽 초과, 한글 파일 150KB 초과).
    """
    stem = re.sub(r"\.[A-Za-z0-9]+$", "", name or "")
    manual = bool(MANUAL_NAME.search(stem) and not BUNDLED_FORM_NAME.search(stem))
    if content == "form":
        # 이름이 신청서·서식 묶음이면 크기와 관계없이 서류(여러 서식을 묶어 커진 파일).
        if not manual and (STRONG_FORM_NAME.search(stem) or re.search(r"서식|양식|신청\s*서류", stem)):
            return "form"
        if pages is not None:
            return "form" if pages <= 10 else "reference"
        return "form" if (size_kb or 0) <= 150 else "reference"
    if content == "no_form":
        # 칸 이름을 못 찾았어도 신청인이 손으로 쓰는 서식 이름이면 서류(인쇄해서 작성). 기관·의사가 쓰는 서류는 제외.
        handwritten = re.search(r"서식|양식|위임서|자기\s*소개서|사용\s*계획서", stem) and not re.search(
            r"통지서|처방전|조사서|조사표|결정|명단|없음|안내", stem)
        return "form" if (STRONG_FORM_NAME.search(stem) or handwritten) and not manual else "reference"
    return attachment_kind(name)


def content_check(raw: bytes, name: str = "") -> tuple[str, int | None]:
    """파일 이름은 보지 않고 내용만으로 신청서(작성할 칸)가 있는지 본다. (form|no_form|scanned|unsupported, PDF 쪽수)."""
    fmt, _ = fill_form.detect_format(raw, name)
    sign = re.compile(r"\(\s*서명|날인|\(인\)")
    if fmt == "pdf":
        text_len, pages = 0, 0
        with pdfplumber.open(io.BytesIO(raw)) as pdf:
            pages = len(pdf.pages)
            for page in pdf.pages[:60]:
                text = page.extract_text() or ""
                text_len += len(text)
                if _field_count(text) >= 2 and (any(_heading(l) for l in text.splitlines()[:14]) or sign.search(text)):
                    return "form", pages
        return ("scanned" if text_len < 30 else "no_form"), pages
    if fmt == "hwpx":
        return ("form" if _analyze_hwpx(raw, "x.hwpx")["fillable_candidate"] else "no_form"), None
    if fmt == "hwp":
        runtime = fill_hwp._resolve_hwplib_runtime()
        if runtime is None:
            return "unsupported", None
        java, jar, classes = runtime
        with tempfile.TemporaryDirectory(prefix="bokji_kind_") as tmp:
            path = Path(tmp) / "a.hwp"
            path.write_bytes(raw)
            proc = subprocess.run([java, "-cp", f"{jar}{os.pathsep}{classes}", "HwpLibTool", "inspect", str(path)],
                                  capture_output=True, text=True, encoding="utf-8", timeout=40, check=False)
        dump = json.loads(proc.stdout) if proc.returncode == 0 and proc.stdout.strip() else {}
        paragraphs = [x.get("text", "") for x in dump.get("paragraphs", [])]
        for table in dump.get("tables", []):
            cells = table.get("cells", [])
            text = "\n".join(c.get("text", "") for c in cells)
            if _field_count(text) >= 2 and (any(_heading(c.get("text", "")) for c in cells[:12])
                                            or any(_heading(x) for x in paragraphs) or sign.search(text)):
                return "form", None
        return "no_form", None
    return "unsupported", None


def attachment_kind(name: str, url: str | None = None) -> str:
    """첨부 이름으로 '서류(form)'와 '참고 자료(reference)'를 나눈다.

    사업안내·지침·공고·조례·매뉴얼은 신청서가 아니다. '안내문 및 신청서'처럼 둘 다 있으면 서류로 본다.
    """
    if url and (known := _attachment_kinds().get(attachment_key(url))):
        return known
    stem = re.sub(r"\.[A-Za-z0-9]+$", "", name or "")
    suffix = Path(name or "").suffix.lower()
    if suffix and suffix not in (".pdf", ".hwp", ".hwpx"):
        return "reference"  # 엑셀·이미지 등은 채울 수 없다. 내려받기만 제공한다.
    # '신청서 작성 매뉴얼'처럼 설명서를 뜻하는 말이 있으면 참고 자료다('안내문 및 신청서'처럼 따로 묶인 경우는 제외).
    if MANUAL_NAME.search(stem) and not BUNDLED_FORM_NAME.search(stem):
        return "reference"
    if FORM_NAME.search(stem) or ATTACH_FORM_NAME.search(stem):
        return "form"
    return "reference" if REFERENCE_NAME.search(stem) or ATTACH_REFERENCE_NAME.search(stem) else "form"


def load_registry() -> dict:
    try:
        return json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"version": 1, "entries": []}


def list_verified_templates(registry: dict | None = None) -> list[dict]:
    """Only records with explicit visual review of the current engine qualify."""
    source = load_registry() if registry is None else registry
    return [{"filenames": e.get("filenames", []), "reviewed_at": e["reviewed_at"],
             "source_sha256": e["source_sha256"], "engine_version": ENGINE_VERSION}
            for e in source.get("entries", [])
            if e.get("source_sha256") and e.get("reviewed_at")
            and e.get("engine_version") == ENGINE_VERSION and e.get("checks", {}).get("visual_review") is True]


def _template_status(raw: bytes, filename: str, registry: dict) -> str:
    digest = hashlib.sha256(raw).hexdigest()
    entries = registry.get("entries", [])
    for entry in entries:
        if (entry.get("source_sha256") == digest
                and entry.get("engine_version") == ENGINE_VERSION
                and entry.get("reviewed_at") and entry.get("checks", {}).get("visual_review") is True):
            return "verified"
    if any(digest == e.get("source_sha256") or filename in e.get("filenames", []) for e in entries):
        return "changed"
    return "new"


def _compact(text: str) -> str:
    return re.sub(r"\s+", "", text)


def _field_count(text: str) -> int:
    compact = _compact(text)
    return sum(bool(re.search(pattern, compact)) for pattern in FIELD_PATTERNS)


def _heading(text: str) -> bool:
    compact = _compact(text)
    return bool(compact and len(compact) < 90 and FORM_TITLE.search(compact)
                and not re.search(r"제출|구비|작성방법|작성예|[。.]$|신청서접수", compact))


def _safe_hwpx_sections(raw: bytes) -> list[tuple[str, etree._Element]]:
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        infos = z.infolist()
        if len(infos) > fill_hwpx.MAX_HWPX_ENTRIES or sum(x.file_size for x in infos) > fill_hwpx.MAX_HWPX_UNCOMPRESSED_BYTES:
            raise ValueError("document_size_limit")
        return [(x.filename, etree.fromstring(z.read(x), parser=etree.XMLParser(resolve_entities=False, no_network=True)))
                for x in infos if re.fullmatch(r"Contents/section\d+\.xml", x.filename)]


def _analyze_hwpx(raw: bytes, filename: str) -> dict:
    scopes: dict[str, set[int]] = {}
    discovered: set[str] = set()
    form_text: list[str] = []
    for section, root in _safe_hwpx_sections(raw):
        paragraphs = root.xpath("./*[local-name()='p']")
        previous_heading = False
        for index, p in enumerate(paragraphs):
            texts = p.xpath(".//*[local-name()='t']/text()")
            text = "\n".join(texts)
            compact = _compact(text)
            tables = p.xpath(".//*[local-name()='tbl']")
            if EXCLUDED.search(compact):
                previous_heading = False
                continue
            if not tables:
                previous_heading = _heading(text)
                continue
            # A short table title or immediately preceding title plus multiple
            # identity labels identifies a form block, not a mention in a guide.
            title = any(_heading(t) for t in texts[:8])
            has_form = (title or previous_heading) and _field_count(text) >= 2
            if has_form:
                scopes.setdefault(section, set()).add(index)
                form_text.append(text)
                for key, label in LABELS.items():
                    if label in compact:
                        discovered.add(label)
            previous_heading = False
    # A standalone named form can have its title only in a header. Still require
    # multiple labels and keep bank/example blocks excluded.
    if not scopes and FORM_NAME.search(filename) and not REFERENCE_NAME.search(filename):
        for section, root in _safe_hwpx_sections(raw):
            for index, p in enumerate(root.xpath("./*[local-name()='p']")):
                text = "\n".join(p.xpath(".//*[local-name()='t']/text()"))
                if p.xpath(".//*[local-name()='tbl']") and _field_count(text) >= 2 and not EXCLUDED.search(_compact(text)):
                    scopes.setdefault(section, set()).add(index)
                    form_text.append(text)
    return {"fillable_candidate": bool(scopes), "method": "form_blocks", "allowed_blocks": scopes,
            "_form_text": "\n".join(form_text),
            "field_labels": sorted(discovered), "reason": "form_blocks_found" if scopes else "no_confirmed_form_block"}


def _analyze_pdf(raw: bytes, filename: str) -> dict:
    scopes = set()
    texts: dict[int, str] = {}
    images = 0
    with pdfplumber.open(io.BytesIO(raw)) as pdf:
        if len(pdf.pages) > MAX_PAGES:
            return {"fillable_candidate": False, "reason": "page_limit"}
        for index, page in enumerate(pdf.pages):
            text = page.extract_text() or ""
            texts[index] = text
            images += len(page.images)
            compact = _compact(text)
            if EXCLUDED.search(compact):
                continue
            title = any(_heading(line) for line in text.splitlines()[:12])
            named_form = bool(FORM_NAME.search(filename) and not REFERENCE_NAME.search(filename))
            if _field_count(text) >= 2 and (title or named_form):
                scopes.add(index)
    # AcroForm labels are not necessarily painted into page text.
    reader = PdfReader(io.BytesIO(raw))
    if FORM_NAME.search(filename) and not REFERENCE_NAME.search(filename):
        for index, page in enumerate(reader.pages):
            for ref in page.get("/Annots", []):
                widget = ref.get_object()
                label = str(widget.get("/TU") or widget.get("/T") or "")
                if widget.get("/Subtype") == "/Widget" and _field_count(label):
                    scopes.add(index)
    # 글자 정보 없이 그림만 있는 PDF는 스캔본이다. 칸 위치를 읽을 수 없다.
    scanned = not scopes and images > 0 and not any(t.strip() for t in texts.values())
    return {"fillable_candidate": bool(scopes), "method": "form_pages", "allowed_pages": scopes,
            "_form_text": "\n".join(texts.get(i, "") for i in sorted(scopes)), "scanned": scanned,
            "field_labels": [], "reason": "form_pages_found" if scopes else ("scanned_image" if scanned else "no_confirmed_form_page")}


def analyze_document(raw: bytes, filename: str) -> dict:
    fmt, _ = fill_form.detect_format(raw, filename)
    if fmt == "hwpx":
        result = _analyze_hwpx(raw, filename)
    elif fmt == "pdf":
        result = _analyze_pdf(raw, filename)
    elif fmt == "hwp":
        # Mixed binary HWP requires an explicit verified scope before filling.
        result = {"fillable_candidate": bool(FORM_NAME.search(filename)),
                  "automatic_allowed": bool(FORM_NAME.search(filename) and not REFERENCE_NAME.search(filename)),
                  "method": "standalone_form", "field_labels": [], "reason": "hwp_scope_needs_review"}
    else:
        result = {"fillable_candidate": False, "reason": "unsupported_format", "field_labels": []}
    result["format"] = fmt
    result.setdefault("automatic_allowed", result["fillable_candidate"])
    return result


def _validate_output(raw: bytes, fmt: str, *, reopen: bool = False) -> bool:
    try:
        if fmt == "pdf":
            return bool(PdfReader(io.BytesIO(raw)).pages)
        if fmt == "hwpx":
            return bool(_safe_hwpx_sections(raw))
        if fmt == "hwp":
            if fill_form.detect_format(raw)[0] != "hwp":
                return False
            if not reopen:
                return True
            runtime = fill_hwp._resolve_hwplib_runtime()
            if runtime is None:
                return False
            java, jar, classes = runtime
            with tempfile.TemporaryDirectory(prefix="bokji_verify_") as tmp:
                path = Path(tmp) / "document.hwp"
                path.write_bytes(raw)
                proc = subprocess.run([java, "-cp", f"{jar}{os.pathsep}{classes}", "HwpLibTool", "inspect", str(path)],
                                      capture_output=True, timeout=20, check=False)
                return proc.returncode == 0 and isinstance(json.loads(proc.stdout), dict)
    except Exception:
        pass
    return False


def prepare_document(raw: bytes, filename: str, profile: dict[str, str], *, registry: dict | None = None) -> dict:
    """Return one document for viewing/download. Never manufacture profile values.

    ``verified`` requires exact original bytes, current engine and recorded visual
    review. ``filled`` means some fields were filled, not that the form is complete.
    ``preview_allowed`` is structural compatibility; the viewer still must render.
    """
    original_name = safe_filename(filename)
    digest = hashlib.sha256(raw).hexdigest()
    result = {"data": raw, "filename": original_name, "format": "unsupported", "status": "manual",
              "filled_count": 0, "filled_labels": [], "manual_labels": [], "warnings": [],
              "template_status": _template_status(raw, filename, registry if registry is not None else load_registry()),
              "fingerprint": digest, "preview_allowed": False, "analysis": {"fillable_candidate": False}}
    if not raw or len(raw) > MAX_BYTES:
        result.update(status="error", warnings=["서류를 열 수 없거나 파일이 너무 큽니다. 원본을 확인해 주세요."])
        return result
    try:
        analysis = analyze_document(raw, filename)
        fmt = analysis["format"]
        original_name = safe_filename(original_name, fmt)
        result["filename"] = original_name
        # Internal scopes contain sets; UI receives only simple descriptive data.
        result["analysis"] = {k: v for k, v in analysis.items() if not k.startswith(("allowed_", "_"))}
        result["format"] = fmt
        if fmt == "pdf" and analysis.get("allowed_pages"):
            # 조례·지침이 붙은 긴 PDF는 신청서 쪽만 미리 보여 준다(1부터 세는 쪽 번호).
            result["preview_pages"] = sorted(i + 1 for i in analysis["allowed_pages"])[:40]
        result["preview_allowed"] = _validate_output(raw, fmt)
        if fmt == "unsupported":
            if fill_form.detect_signature(raw) == "drm":
                result.update(template_status="unsupported", status="drm", warnings=[
                    "기관 보안 프로그램(DRM)으로 잠긴 파일이라 집 컴퓨터나 휴대폰에서는 열리지 않습니다. "
                    "아래 방법으로 주민센터·담당 기관에서 신청서를 받아 주세요."])
            else:
                result.update(template_status="unsupported", warnings=["이 파일은 화면 미리보기를 지원하지 않습니다. 원본 파일을 저장해 열어 주세요."])
            return result
        if not analysis["fillable_candidate"]:
            result["status"] = "reference"
            result["warnings"] = (["사진처럼 스캔된 서류라 칸 위치를 읽을 수 없습니다. 인쇄해서 아래 ‘옮겨 적을 내용’을 보고 직접 써 주세요."]
                                  if analysis.get("scanned") else
                                  ["자동으로 채울 신청서 영역을 확인하지 못했습니다. 서류를 보고 직접 작성할 부분을 확인해 주세요."])
            return result
        if not analysis["automatic_allowed"]:
            result["warnings"] = ["안내문과 신청서가 함께 있는 한글 파일입니다. 아직 작성 영역을 안전하게 구분하지 못해 원본을 보여 드립니다. 필요한 신청서는 직접 작성해 주세요."]
            return result
        if not any(str(v or "").strip() for k, v in profile.items() if not k.startswith("apply_date")):
            result["warnings"] = ["내용을 확인한 뒤 아래에 정보를 입력하면 서류를 채울 수 있습니다."]
            return result
        # 서류마다 다른 날짜·전화 표기를 신청서 부분의 글자에서 읽어 맞춘다.
        # HWP는 기입 엔진이 구조를 읽은 뒤 같은 방식으로 맞춘다.
        def fill(styles):
            if fmt == "hwp":
                data, report = fill_form.fill_form(raw, filename, profile=profile, styles=styles)
                return data, report, styles or report.get("formats")
            styles = styles or field_format.detect_document_styles(analysis.get("_form_text", ""))
            adapted = field_format.adapt_profile(profile, styles)
            if fmt == "hwpx":
                data, report = fill_hwpx.fill_hwpx_bytes(raw, profile=adapted, allowed_blocks=analysis["allowed_blocks"])
            else:
                data, report = fill_pdf.fill_pdf_bytes(raw, profile=adapted, allowed_pages=analysis["allowed_pages"])
            return data, report, styles

        token = (fm.BENEFICIARY_IS_APPLICANT.set(fm.beneficiary_is_applicant(analysis["_form_text"]))
                 if fmt != "hwp" and "_form_text" in analysis else None)
        try:
            data, report, styles = fill(None)
            # 서류 표기(010-1234-5678, 1950년 1월 1일)가 좁은 칸에 안 들어가면 짧은 표기로 한 번 더 시도한다.
            no_room = any(x.get("reason") in ("text_overflow", "no_room", "box_too_small") for x in report.get("skipped_fields", []))
            if no_room and any(profile.get(k) for k in ("applicant.birth_date", "applicant.phone", "proxy.phone")):
                retry = fill(field_format.COMPACT_STYLES)
                if int(retry[1].get("filled_count", 0)) > int(report.get("filled_count", 0)) and retry[1].get("status") not in ("error", "unsupported"):
                    data, report, styles = retry
        finally:
            if token is not None:
                fm.BENEFICIARY_IS_APPLICANT.reset(token)
        if styles:
            result["formats"] = styles
        if report.get("status") in ("error", "unsupported"):
            result["warnings"] = ["이 서류는 자동 작성하지 못했습니다. 원본을 보고 직접 작성해 주세요."]
            return result
        if not _validate_output(data, fmt, reopen=True):
            result.update(status="error", warnings=["이 파일은 프로그램이 다시 저장할 수 없는 형식이 들어 있어 자동으로 채우지 못했습니다. "
                                                    "원본을 인쇄해서 아래 ‘옮겨 적을 내용’을 보고 써 주세요."])
            return result
        filled = int(report.get("filled_count", 0))
        result.update(data=data, status="filled" if filled else "manual", filled_count=filled)
        if filled:
            result["filename"] = safe_filename(original_name, fmt, prefix="작성됨_")
        result["filled_labels"] = list(dict.fromkeys(LABELS[f["field_key"]] for f in report.get("filled_fields", []) if f.get("field_key") in LABELS))
        skipped = report.get("skipped_fields", [])
        result["manual_labels"] = list(dict.fromkeys(LABELS[f["field_key"]] for f in skipped if f.get("field_key") in LABELS))
        result["warnings"] = ["채워진 내용과 빈칸을 확인하고, 서명·날인은 직접 해 주세요."]
        if any(x.get("reason") in ("text_overflow", "no_room", "box_too_small") for x in skipped):
            result["warnings"].append("칸이 좁아 넣지 못한 내용이 있습니다. 빈칸을 확인해 직접 작성해 주세요.")
        if fmt == "pdf" and any(x.get("mode") == "acroform_overlay" for x in report.get("filled_fields", [])):
            result["warnings"].append("이 PDF는 화면 확인·인쇄용입니다. 온라인 제출 화면의 입력값으로 자동 전달되지는 않습니다.")
        if any(float(x.get("fontsize", 10)) < 8 for x in report.get("filled_fields", [])):
            result["warnings"].append("일부 칸의 글씨가 작습니다. 확대해서 읽을 수 있는지 확인해 주세요.")
        return result
    except Exception:
        result.update(status="error", warnings=["서류 구조를 확인하지 못했습니다. 원본 파일을 저장해 확인해 주세요."])
        return result
