def fingerprint_inputs(payload: Any) -> str:
    """Compare generated bytes with current inputs without storing a second profile."""
    return hashlib.sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"), default=str).encode()).hexdigest()


def safe_filename(filename: str, fmt: str | None = None, *, prefix: str = "") -> str:
    """Use the actual supported format and never return a supplied path."""
    name = str(filename).replace("\\", "/").rsplit("/", 1)[-1]
    name = re.sub(r'[\x00-\x1f\x7f:*?"<>|]', "_", name).strip(" .") or "서류"
    suffix = f".{fmt}" if fmt in ("pdf", "hwp", "hwpx") else Path(name).suffix
    stem = Path(name).stem if Path(name).suffix else name
    stem = stem.strip(" .") or "서류"
    return prefix + stem[:max(1, 160 - len(prefix) - len(suffix))] + suffix


def list_documents(svc: dict) -> list[dict]:
    result, seen = [], set()
    for item in svc.get("form_files", []):
        url = str(item.get("url") or "")
        if not url or url in seen:
            continue
        seen.add(url)
        name = str(item.get("name") or "첨부 서류")
        result.append({"id": hashlib.sha256(url.encode()).hexdigest()[:16], "name": name,
                       "url": url, "filename_hint": bool(FORM_NAME.search(name)), "kind": attachment_kind(name, url)})
    return result


